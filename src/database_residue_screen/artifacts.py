import copy
import hashlib
import json
from pathlib import Path

from . import __version__
from .contracts import ContractError, read_json, read_table, schema, validate_record, write_table
from .design import check_design, digest, member
from .example import save_json


def software_record() -> dict:
    root = Path(__file__).parent
    checksum = hashlib.sha256()
    for path in sorted(path for path in root.rglob("*") if path.suffix in {".py", ".json"}):
        checksum.update(str(path.relative_to(root)).encode("utf-8") + b"\0")
        checksum.update(path.read_bytes())
    return dict(version=__version__, code_sha256=checksum.hexdigest())


def inventory_schema() -> dict:
    definition = copy.deepcopy(schema("queries"))
    definition["properties"].update(canonical_id={"type": "string", "pattern": "^seq_[a-f0-9]{64}$"}, length={"type": "integer", "minimum": 1})
    definition["required"].extend(["canonical_id", "length"])
    return definition


def coverage_schema() -> dict:
    properties = dict(query_id={"type": "string"}, query_length={"type": "integer", "minimum": 1},
                      covered_bases={"type": "integer", "minimum": 0}, component_count={"type": "integer", "minimum": 0},
                      structurally_complete={"type": "integer", "enum": [0, 1]}, physical_architecture_verified={"type": "integer", "enum": [0, 1]})
    return dict(type="object", additionalProperties=False, required=list(properties), properties=properties)


def normalised_coverage(rows: list[dict]) -> list[dict]:
    return [dict(row, structurally_complete=int(row["structurally_complete"]),
                 physical_architecture_verified=int(row["physical_architecture_verified"])) for row in rows]


def write_preflight(study_path: Path, destination: Path) -> dict:
    report = check_design(study_path)
    destination.mkdir(parents=True, exist_ok=False)
    save_json(destination / "preflight.json", report)
    write_table(destination / "query_inventory.tsv", report["inventory"], inventory_schema())
    write_table(destination / "component_coverage.tsv", normalised_coverage(report["component_coverage"]), coverage_schema())
    artifacts = []
    for role, filename, kind, rows in (
        ("preflight", "preflight.json", "json", None),
        ("query_inventory", "query_inventory.tsv", "tsv", len(report["inventory"])),
        ("component_coverage", "component_coverage.tsv", "tsv", len(report["component_coverage"])),
    ):
        artifacts.append(dict(role=role, path=filename, sha256=digest(destination / filename), format=kind, rows=rows))
    manifest = dict(schema_version="1.0.0", study_id=report["study_id"], study_sha256=digest(study_path),
                    software=software_record(), stage="preflight", artifacts=artifacts)
    validate_record(manifest, schema("manifest"))
    save_json(destination / "manifest.json", manifest)
    return report


def validate_outputs(study_path: Path, directory: Path) -> dict:
    manifest = read_json(directory / "manifest.json", schema("manifest"))
    if manifest["study_sha256"] != digest(study_path):
        raise ContractError("Output belongs to a different study design")
    if manifest["software"] != software_record():
        raise ContractError("Output was generated by a different validator version or code checksum")
    study = read_json(study_path, schema("study"))
    if manifest["study_id"] != study["study_id"]:
        raise ContractError("Output study ID disagrees with design")
    if manifest["stage"] != "preflight":
        raise ContractError("Full search-bundle certification is not implemented; validate execution rows separately")
    roles = {artifact["role"]: artifact for artifact in manifest["artifacts"]}
    paths = {artifact["path"] for artifact in manifest["artifacts"]}
    if len(roles) != len(manifest["artifacts"]) or len(paths) != len(roles) or set(roles) != {"preflight", "query_inventory", "component_coverage"}:
        raise ContractError("Missing, duplicate or unexpected preflight artifact roles/paths")
    expected_files = {"manifest.json"} | paths
    actual_files = {str(path.relative_to(directory)) for path in directory.rglob("*") if path.is_file()}
    if actual_files != expected_files:
        raise ContractError("Output directory contains missing or undeclared artifacts")
    for artifact in roles.values():
        path = member(directory, artifact["path"])
        if digest(path) != artifact["sha256"]:
            raise ContractError(f"Artifact checksum mismatch: {artifact['role']}")
    report = read_json(member(directory, roles["preflight"]["path"]))
    current = check_design(study_path)
    if report != current:
        raise ContractError("Preflight is stale or inconsistent with current input evidence")
    for name, expected, definition in (
        ("query_inventory", report["inventory"], inventory_schema()),
        ("component_coverage", normalised_coverage(report["component_coverage"]), coverage_schema()),
    ):
        artifact = roles[name]
        rows = read_table(member(directory, artifact["path"]), definition)
        if artifact["format"] != "tsv" or artifact["rows"] != len(rows) or rows != expected:
            raise ContractError(f"Output structure or content mismatch: {name}")
    if roles["preflight"]["format"] != "json" or roles["preflight"]["rows"] is not None:
        raise ContractError("Wrong preflight JSON artifact declaration")
    return dict(valid=True, stage="preflight", scope=report["scope"], ready_for_freeze=report["ready_for_freeze"], artifact_count=len(roles))


def freeze_design(study_path: Path, destination: Path) -> dict:
    report = check_design(study_path)
    if not report["ready_for_freeze"]:
        blockers = sorted({issue["code"] for issue in report["issues"] if issue["severity"] == "blocker"})
        raise ContractError("Design freeze blocked: " + ", ".join(blockers))
    lock = dict(schema_version="1.0.0", study_id=report["study_id"], scope=report["scope"], gate="G0_only",
                evidence_semantics="File and declaration completeness; not independent authentication or completed scientific validation",
                study_sha256=digest(study_path), input_sha256=report["input_sha256"], software=software_record(),
                production_search_ready=False, scientific_results_validated=False)
    save_json(destination, lock)
    return lock
